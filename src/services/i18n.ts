export const getTranslation = (lang: Language, key: string, params?: Record<string, string | number>): string => {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = dict[key] || TRANSLATIONS.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
};

// Helper: Format distance with natural unit
export const formatDistance = (km: number, lang: Language): string => {
  if (lang === 'bn') {
    return `${km} কিমি`;
  }
  return `${km} km`;
};

// Helper: Format count of units
export const formatUnits = (units: number, lang: Language): string => {
  if (lang === 'bn') {
    return `${units} ইউনিট`;
  }
  return units === 1 ? `${units} unit` : `${units} units`;
};

// Helper: Format donations count
export const formatDonationCount = (count: number, lang: Language): string => {
  if (lang === 'bn') {
    return `${count} বার রক্তদান`;
  }
  return `${count} donations`;
};

